import { describe, expect, it } from 'vitest';
import { resample } from '../../../src/zoo/higgs/resample.ts';
import { expectClose } from '../../gpu.ts';

/** torchaudio.functional.resample of sin(0.37·i) + 0.25·cos(1.9·i), i < 30,
 *  in f32. */
const CASES = [
  {
    from: 24000,
    to: 16000,
    want: [
      0.2108059, 0.3475274, 1.051666, 0.875095, 0.8701676, 0.3372981, -0.2200067, -0.5928122,
      -1.090017, -0.7994488, -0.8487226, 0.006913295, 0.1949587, 0.9491783, 0.8872837, 0.9518282,
      0.5127921, -0.06577077, -0.4160606, -1.092452,
    ],
  },
  {
    from: 16000,
    to: 24000,
    want: [
      0.2499143, 0.3016797, 0.2783851, 0.4766709, 0.9151695, 1.197288, 1.059041, 0.774378,
      0.7292403, 0.8950325, 0.8743784, 0.4655635, -0.0381993, -0.2474982, -0.195961, -0.2822258,
      -0.681742, -1.093253, -1.135913, -0.8781106, -0.729259, -0.8666988, -0.9855425, -0.7362081,
      -0.2233083, 0.127147, 0.1427146, 0.1333676, 0.4290366, 0.9071645, 1.137786, 0.9793174,
      0.7593209, 0.8155477, 1.013702, 0.9466835, 0.506445, 0.04958639, -0.07640228, -0.0328524,
      -0.2109127, -0.6330681, -1.052046, -1.128251, -0.6066854,
    ],
  },
  {
    from: 48000,
    to: 24000,
    want: [
      0.1276895, 0.6354629, 1.011376, 0.7940572, 0.1764477, -0.5227795, -0.9681759, -0.8918399,
      -0.3513483, 0.3610289, 0.9053543, 0.9600978, 0.501188, -0.1494994, -0.9049926,
    ],
  },
  {
    from: 44100,
    to: 24000,
    want: [
      0.1428079, 0.561684, 1.021355, 0.8661705, 0.4189235, -0.2475195, -0.8275571, -0.9656373,
      -0.7876239, -0.1205921, 0.4526238, 0.9621044, 0.9382858, 0.544726, -0.05164224, -0.7983567,
      -0.5990429,
    ],
  },
];

const signal = Float32Array.from(
  { length: 30 },
  (_, i) => Math.sin(0.37 * i) + 0.25 * Math.cos(1.9 * i),
);

describe('resample', () => {
  it.each(CASES)('$from Hz to $to Hz as torchaudio does', ({ from, to, want }) => {
    expectClose(resample(signal, from, to), want, { atol: 1e-6, rtol: 1e-5 });
  });

  it('returns the samples as they are at the same rate', () => {
    expect(resample(signal, 24_000, 24_000)).toBe(signal);
  });

  it('rejects a rate that is not a positive integer', () => {
    expect(() => resample(signal, 44_100.5, 24_000)).toThrow(/must be positive integers/);
    expect(() => resample(signal, 0, 24_000)).toThrow(/must be positive integers/);
  });
});
